/**
 * **这套东西挂在哪个路径下，由页面自己所在的位置推出来。**
 *
 * 组件默认把所有资源地址从**站点根**推出去（`/packages/onlyoffice/<版本>/…`，
 * 见 `src/const/index.ts` 的 `buildStaticResource`）。而装机时它不在站点根上
 * ——站点根归别的应用用，这一套挂在 `/oow` 底下。
 * 不设这一格的话，编辑器会去 `/packages/…` 要东西，**每一条都 404**，
 * 而症状是**页面一直转圈**（接入页是「编辑器打不开」，自检页是停在「正在跑…」），
 * 一点都不指向这里。
 *
 * ── 为什么单独一个文件 ────────────────────────────────────────────────────
 *
 * 本 PoC 有**两个**入口会开编辑器（`embed.ts` 与 `static-check.ts`）。
 * 2026-09-04 头一版只在 `embed.ts` 里做了这件事，于是挂在前缀下跑那一趟
 * **七条断言全红**——而红的原因不是接入页，是自检页那一半没跟上。
 * 同一件事写第二遍就会漏第二处，所以收成一份。
 *
 * ⚠ **推出来，不配出来。** 写成配置项等于给「挂在哪」造第二份事实，
 * 而两份对不上的样子正是上面那句「一直转圈」。页面的地址本身就是答案。
 *
 * ⚠ 末尾拼的那个 `/packages` 不能省。它让**挂在根上与挂在前缀下走同一条代码路径、
 * 盘上也是同一个布局**：根上得到 `/packages/onlyoffice/<版本>`（与不设这一格时逐字相同），
 * 挂在 `/oow` 下得到 `/oow/packages/onlyoffice/<版本>`。
 * 少了它，两种部署的目录结构会不一样，而「只在其中一种下试过」是这条链上最贵的坑。
 */
import { OnlyOfficeManager } from "../../src";

/** 这个页面所在的目录（不含末尾斜杠）。挂在站点根上时是空串。 */
export function 本页挂载前缀(): string {
  return new URL(".", location.href).pathname.replace(/\/+$/, "");
}

/**
 * 按本页所在位置，告诉组件去哪儿取那 1.6 GB 静态资源。
 *
 * **每个会开编辑器的入口都要在开之前调一次。**
 */
export function 按本页位置登记静态资源(): void {
  OnlyOfficeManager.registerStaticResource({ cdnOrigin: 本页挂载前缀() + "/packages" });
}
