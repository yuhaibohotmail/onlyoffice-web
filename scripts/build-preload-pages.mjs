#!/usr/bin/env node
/**
 * 生成「只预热一个编辑器」的那几份预载页。
 *
 *   node scripts/build-preload-pages.mjs          # 写进 vendor 那棵树
 *   node scripts/build-preload-pages.mjs --check  # 只核在不在、内容对不对，不写
 *
 * 由 `scripts/extract-assets.mjs` 的后处理自动调一次；改了这里之后单独跑一遍就行，
 * 不必再传一趟 2 GB。
 *
 * ── 在解决什么 ──────────────────────────────────────────────────────────────
 *
 * 组件在挂编辑器之前先塞一个隐藏 iframe 去预热缓存（`src/util/initialize.ts`），
 * 指的是上游那份 `web-apps/apps/api/documents/preload.html`。**那一份把四个编辑器
 * 全预热一遍**，与这次要开的是什么文档无关：
 *
 *   sdkjs/cell/sdk-all.js    30.9 MB     ← 开 docx 用不到
 *   sdkjs/word/sdk-all.js    27.5 MB
 *   sdkjs/slide/sdk-all.js   27.0 MB     ← 用不到
 *   sdkjs/visio/sdk-all.js   22.7 MB     ← 用不到
 *   四个 sdk-all-min.js 合计 11.7 MB     ← 其中三个用不到
 *   四份 app.css 合计         2.3 MB     ← 其中三份用不到
 *
 * 实测（`node scripts/measure-payload.mjs`，一份 docx，编辑器档，冷载）：
 * 上游那份 437 请求 221.7 MB；只保留 word 那一份之后 141.1 MB，首屏时间不变。
 *
 * ⚠ **`sdk-all-min.js` 不是 `sdk-all.js` 的压缩版，是引导包。**
 * `sdkjs/word/sdk-all-min.js` 里那个 `loadSdk()`：除非 `window['AscNotLoadAllScript']`
 * 为真，否则在引导包之上再去拉整份 `sdk-all.js`。把那个标志注进编辑器页试过一次
 * ——**编辑器 120 秒没就绪**。所以每个编辑器那 20–30 MB 是引擎本身，省不掉，
 * 能省的只是「这次用不到的那三个引擎」。
 *
 * ── 这几份页面与上游那份差在哪 ──────────────────────────────────────────────
 *
 * 一、只提这一个编辑器要的东西。
 *
 * 二、**`sdk-all.js` 用 `<link rel="preload">`，不用 `<script>`。**
 * 上游那份是真 `<script>`，于是那个隐藏 iframe 会真的解析执行 27.5 MB
 * ——而预热要的只是「字节进缓存」，不是「代码跑起来」。
 * 构造 API 用的 `asc_docs_api` / `spreadsheet_api` 在引导包里就有，
 * 所以引导包仍然是真 `<script>`。
 * ⚠ 这一条要量着改：`rel=preload` 拿到的字节如果没能给编辑器 iframe 用上，
 * 同一份东西会下两遍，而**总字节会涨、不会报错**。判据就是 measure-payload 的总字节。
 *
 * 三、许可声明照抄上游那份里的那一段（从原文现取，不在这里写第二份），
 * 另加一行「这是改过的版本」。
 *
 * ── 退出码 ──────────────────────────────────────────────────────────────────
 *
 *   0  写好了 / --check 全对
 *   1  --check 发现缺页或内容对不上
 *   2  **一份都没处理**（找不到原文那份 preload.html）——与「都对」不是一回事
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { SDK_ROOT, SDK_VERSION } from "../config.mjs";

/** 预载页与原文那份同目录。 */
const DOCUMENTS_DIR = path.join(SDK_ROOT, "onlyoffice", SDK_VERSION, "web-apps/apps/api/documents");
const 原文 = path.join(DOCUMENTS_DIR, "preload.html");

/**
 * 每个编辑器应用预热什么。
 *
 * `sdk` 是它 `app.js` 里 `sdk:` 那一行指的目录——**不是按应用名推出来的**：
 * `pdfeditor` 用的是 `word` 那一份（`apps/pdfeditor/main/app.js` 第 58 行）。
 * 换版本时这张表要照那几行核一遍，`--check` 会连这个一起核。
 */
export const 预载页 = [
  { app: "documenteditor", sdk: "word" },
  { app: "spreadsheeteditor", sdk: "cell" },
  { app: "presentationeditor", sdk: "slide" },
  { app: "visioeditor", sdk: "visio" },
  { app: "pdfeditor", sdk: "word" },
];

export const 预载页文件名 = (app) => `preload-${app}.html`;

const die = (码, m) => {
  console.error("✗ " + m);
  process.exit(码);
};

/** 从原文那份里取许可声明那一整块注释，一个字不改地带进生成物。 */
function 取许可声明(原文内容) {
  const m = 原文内容.match(/\/\*\r?\n \* Copyright \(C\) Ascensio System SIA[\s\S]*?\*\//);
  if (!m) die(2, `原文 preload.html 里没找到许可声明那一段：${原文}`);
  return m[0];
}

function 渲染(app, sdk, 许可声明) {
  return `<!DOCTYPE html>
<html>
<head>
    <title>ONLYOFFICE Documents</title>
    <meta http-equiv="Content-Type" content="text/html; charset=utf-8" />
    <style type="text/css"></style>
</head>
<body>
    <script>
${许可声明}

/*
 * NOTE: This file is NOT part of the upstream ONLYOFFICE distribution.
 * It is generated by scripts/build-preload-pages.mjs in this project, from
 * web-apps/apps/api/documents/preload.html, so that the hidden warm-up frame
 * fetches one editor's bundles instead of all four. Do not edit it by hand --
 * regenerate it. This is a modified version of ONLYOFFICE, developed by
 * Ascensio System SIA.
 */

void 0;

</script>

    <script type="text/javascript" src="../../../vendor/jquery/jquery.min.js"></script>
    <script type="text/javascript" src="../../../vendor/socketio/socket.io.min.js"></script>
    <script type="text/javascript" src="../../../vendor/xregexp/xregexp-all-min.js"></script>
    <script type="text/javascript" src="../../../../sdkjs/common/AllFonts.js"></script>
    <script type="text/javascript" src="../../../../sdkjs/${sdk}/sdk-all-min.js"></script>
    <link rel="preload" as="script" href="../../../../sdkjs/${sdk}/sdk-all.js"/>
    <link rel="preload" as="script" href="../../../apps/${app}/main/app.js"/>
    <link rel="preload" as="style" href="../../../apps/${app}/main/resources/css/app.css"/>
    <div id="editor_sdk"></div>
    <script type="text/javascript">
        window['AscNotLoadAllScript'] = true;
        // 引导包里有哪个构造函数按应用而定（word / slide 是 asc_docs_api，cell 是
        // spreadsheet_api，visio 两个都没有）。取不到就只预热字节、不预热字体——
        // **不许在这里抛**：这个 iframe 抛了没有任何人看得见，而编辑器照样能起来，
        // 于是它会变成一处「少了预热而没人知道」。
        (function () {
            var Ctor = window['Asc'] && (window['Asc']['asc_docs_api'] || window['Asc']['spreadsheet_api']);
            if (!Ctor) return;
            try {
                new Ctor({ 'id-view': 'editor_sdk' }).asc_loadFontsFromServer();
            } catch (e) {
                if (window.console && console.warn) console.warn('[preload] font warm-up skipped:', e);
            }
        })();
    </script>
</body>
</html>
`;
}

/** 核一遍那张表与 `app.js` 里 `sdk:` 那一行还对得上。 */
function 核sdk归属() {
  const 坏的 = [];
  for (const { app, sdk } of 预载页) {
    const appJs = path.join(SDK_ROOT, "onlyoffice", SDK_VERSION, `web-apps/apps/${app}/main/app.js`);
    if (!fs.existsSync(appJs)) {
      坏的.push(`${app}：找不到 app.js（${appJs}）`);
      continue;
    }
    const m = fs.readFileSync(appJs, "utf8").match(/sdk\s*:\s*'\.\.\/\.\.\/sdkjs\/([a-z]+)\/sdk-all-min'/);
    if (!m) 坏的.push(`${app}：app.js 里没读到 sdk: 那一行`);
    else if (m[1] !== sdk) 坏的.push(`${app}：表里写的是 ${sdk}，app.js 里实际是 ${m[1]}`);
  }
  return 坏的;
}

function main() {
  const CHECK = process.argv.includes("--check");

  if (!fs.existsSync(原文)) {
    die(2, `找不到原文：${原文}\n  先跑 node scripts/extract-assets.mjs`);
  }
  const 许可声明 = 取许可声明(fs.readFileSync(原文, "utf8"));

  const 归属问题 = 核sdk归属();
  if (归属问题.length) {
    console.error("✗ 预载页那张表与 app.js 对不上：");
    for (const s of 归属问题) console.error("    " + s);
    process.exit(CHECK ? 1 : 2);
  }

  let 不对 = 0;
  for (const { app, sdk } of 预载页) {
    const 目标 = path.join(DOCUMENTS_DIR, 预载页文件名(app));
    const 内容 = 渲染(app, sdk, 许可声明);
    if (CHECK) {
      const 现有 = fs.existsSync(目标) ? fs.readFileSync(目标, "utf8") : null;
      if (现有 === null) {
        console.error(`  ✗ 缺 ${预载页文件名(app)}`);
        不对++;
      } else if (现有 !== 内容) {
        console.error(`  ✗ ${预载页文件名(app)} 与现在该生成的内容不一样（重跑一次本脚本）`);
        不对++;
      } else {
        console.log(`  ✓ ${预载页文件名(app)}（sdkjs/${sdk}）`);
      }
    } else {
      fs.writeFileSync(目标, 内容);
      console.log(`  → ${预载页文件名(app)}  预热 sdkjs/${sdk} + apps/${app}`);
    }
  }

  if (CHECK && 不对) {
    console.error(`✗ ${不对} 份对不上`);
    process.exit(1);
  }
  console.log(CHECK ? `✓ ${预载页.length} 份预载页都在、都是最新的` : `✓ 写好 ${预载页.length} 份预载页：${DOCUMENTS_DIR}`);
}

// ⚠ 判「是不是被直接跑的」要比路径，别比 `file://` 拼出来的字符串：
// Windows 上 `import.meta.url` 是 `file:///E:/…`（三个斜杠），拼出来的是两个，
// 于是恒不相等——**表现是这个脚本单独跑什么都不做，而且不报错**。
if (path.resolve(process.argv[1] ?? "") === path.resolve(fileURLToPath(import.meta.url))) main();
